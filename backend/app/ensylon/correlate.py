"""CORRELATE — group anomalous signals into incidents.

Density clustering over a four-dimension similarity space, behind a hard
shared-context gate, with candidate pairs generated by blocking.

The three ideas, and why each is here:

**Similarity, not a time window.** Grouping whatever fired in the same five
minutes is how two unrelated incidents end up in one ticket. Similarity
combines time proximity with service identity, dependency topology, and log
template overlap, so co-occurrence alone carries only 30% of the weight.

**The shared-context gate.** Similarity alone never groups anything. Two
signals may only cluster if they *also* share something concrete: the same
service, a direct dependency edge, or a trace id. This is the primary defence
against the worst failure in this problem — a false merge, which hides a real
incident inside another's ticket. A false split merely costs a duplicate.
Those errors are not symmetric, so the gate is deliberately strict.

**Blocking.** Scoring every pair is O(n²). Instead, candidate pairs are
generated from blocks (same service, same trace, dependency neighbours within
the window); pairs sharing no block are never scored, because the gate would
reject them anyway. The distance matrix is built sparse, and DBSCAN treats
unstored pairs as infinitely far apart — so the saving is real, not cosmetic.
"""

from __future__ import annotations

import math
import re
from collections import defaultdict
from dataclasses import dataclass, field
from datetime import timedelta
from itertools import combinations

import networkx as nx
import numpy as np
from scipy.sparse import csr_matrix
from sklearn.cluster import DBSCAN
from sklearn.neighbors import sort_graph_by_row_values

from .signal import Signal

# --------------------------------------------------------------------------
# tunables
# --------------------------------------------------------------------------

W_TIME = 0.30
W_SERVICE = 0.25
W_DEPENDENCY = 0.25
W_TEMPLATE = 0.20

WINDOW_BASE_MIN = 5.0     # adaptive window floor
WINDOW_MAX_MIN = 15.0     # ...and ceiling
TIME_SCALE_MIN = 4.0      # exponential decay constant

EPS = 0.62                # DBSCAN radius in distance units (1 - similarity)
MIN_SAMPLES = 2

# Hop distance → closeness. Beyond three hops two services are effectively
# unrelated for incident purposes, whatever the graph says.
_HOP_CLOSENESS = {0: 1.0, 1: 0.75, 2: 0.45, 3: 0.15}


# --------------------------------------------------------------------------
# dependency graph
# --------------------------------------------------------------------------


class DependencyGraph:
    """Service topology, used for both correlation and causality.

    Directed, because "A calls B" is not the same claim as "B calls A" — the
    causal engine depends on that direction. Correlation asks only about
    distance, so it reads the undirected view.
    """

    def __init__(self, edges: set[tuple[str, str]] | None = None) -> None:
        self.graph = nx.DiGraph()
        for caller, callee in edges or set():
            self.graph.add_edge(caller, callee)
        self._undirected = self.graph.to_undirected()
        self._hops: dict[tuple[str, str], int | None] = {}

    def add_edges(self, edges: set[tuple[str, str]]) -> None:
        for caller, callee in edges:
            self.graph.add_edge(caller, callee)
        self._undirected = self.graph.to_undirected()
        self._hops.clear()

    def hops(self, a: str, b: str) -> int | None:
        """Undirected shortest path length, or None if unreachable."""
        if a == b:
            return 0
        key = (a, b) if a <= b else (b, a)
        if key in self._hops:
            return self._hops[key]
        try:
            distance = nx.shortest_path_length(self._undirected, a, b)
        except (nx.NetworkXNoPath, nx.NodeNotFound):
            distance = None
        self._hops[key] = distance
        return distance

    def closeness(self, a: str, b: str) -> float:
        hop = self.hops(a, b)
        if hop is None:
            return 0.0
        return _HOP_CLOSENESS.get(hop, 0.0)

    def has_direct_edge(self, a: str, b: str) -> bool:
        return self.graph.has_edge(a, b) or self.graph.has_edge(b, a)

    def neighbours(self, service: str) -> set[str]:
        if service not in self._undirected:
            return set()
        return set(self._undirected.neighbors(service))

    def downstream_of(self, service: str) -> set[str]:
        """Everything reachable *following* call direction — the blast radius."""
        if service not in self.graph:
            return set()
        return set(nx.descendants(self.graph, service))

    def upstream_of(self, service: str) -> set[str]:
        if service not in self.graph:
            return set()
        return set(nx.ancestors(self.graph, service))


