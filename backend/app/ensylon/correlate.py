# similarity
# --------------------------------------------------------------------------


def _minutes_apart(a: Signal, b: Signal) -> float:
    return abs((a.timestamp - b.timestamp).total_seconds()) / 60.0


def time_proximity(a: Signal, b: Signal) -> float:
    """Exponential decay, hard-zero past the adaptive ceiling."""
    dt = _minutes_apart(a, b)
    if dt > WINDOW_MAX_MIN:
        return 0.0
    return math.exp(-dt / TIME_SCALE_MIN)


def service_affinity(a: Signal, b: Signal) -> float:
    if a.service == b.service:
        return 1.0 if (a.component or "") == (b.component or "") else 0.85
    return 0.0


def template_similarity(a: Signal, b: Signal) -> float:
    """Same mined template is a strong match; otherwise token overlap.

    Token Jaccard is the fallback that carries correlation across sources —
    a Grafana alert and an application log describing the same failure share
    vocabulary even though neither has a template id.
    """
    if a.template_id and b.template_id and a.template_id == b.template_id:
        return 1.0
    tokens_a = _tokens(a)
    tokens_b = _tokens(b)
    if not tokens_a or not tokens_b:
        return 0.0
    overlap = len(tokens_a & tokens_b)
    return overlap / len(tokens_a | tokens_b)


_STOP = {"the", "a", "an", "in", "on", "of", "to", "for", "is", "was", "and", "at", "by"}

# Alarm notifications are mostly boilerplate: every CloudWatch alarm ever
# raised says "Threshold Crossed: 1 datapoint ... was greater than the
# threshold". Left in, two completely unrelated alarms score as near-identical
# text purely on that shared frame, which is precisely the wrong answer. The
# discriminating content of a metric alarm is its metric name, not its prose.
_BOILERPLATE = {
    "threshold", "crossed", "datapoint", "datapoints", "greater", "less",
    "than", "alarm", "state", "value", "values", "error", "errors", "failed",
    "failure", "exceeded", "exceeds",
}


_CAMEL_BOUNDARY = re.compile(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])")
_WORD = re.compile(r"[a-z][a-z0-9]{2,}")


def _tokens(signal: Signal) -> set[str]:
    """Comparable vocabulary for a signal.

    Metric names are camelCase identifiers, not prose: left whole,
    `DatabaseConnections` shares no token with the log line "connection pool
    exhausted" that describes the very same failure — so the strongest piece
    of evidence linking a symptom to its cause scores exactly zero. Splitting
    on case boundaries and normalising trivial plurals restores that link,
    which is what lets a log burst be attributed to the right metric alarm
    when a service depends on several failing things at once.
    """
    raw = f"{signal.message} {signal.metric or ''} {signal.component or ''}"
    spaced = _CAMEL_BOUNDARY.sub(" ", raw).lower()
    found = _WORD.findall(spaced)

    tokens: set[str] = set()
    for token in found:
        if token in _STOP or token in _BOILERPLATE:
            continue
        # Fold simple plurals so "connections" matches "connection". Not a
        # real stemmer - just enough to stop trivial morphology from hiding
        # an obvious match, without the false merges aggressive stemming
        # would cause.
        if len(token) > 4 and token.endswith("s") and not token.endswith("ss"):
            token = token[:-1]
        if token not in _STOP and token not in _BOILERPLATE:
            tokens.add(token)
    return tokens


@dataclass
class SimilarityBreakdown:
    """Kept per accepted pair so a cluster can explain how it was formed."""

    time: float
    service: float
    dependency: float
    template: float
    total: float
    gate_reason: str


def similarity(
    a: Signal, b: Signal, graph: DependencyGraph
) -> SimilarityBreakdown | None:
    """Score a pair, or return None if the shared-context gate rejects it."""
    gate = _gate_reason(a, b, graph)
    if gate is None:
        return None

    t = time_proximity(a, b)
    if t == 0.0:
        return None  # outside the window entirely

    s = service_affinity(a, b)
    d = graph.closeness(a.service, b.service)
    tpl = template_similarity(a, b)
    total = W_TIME * t + W_SERVICE * s + W_DEPENDENCY * d + W_TEMPLATE * tpl
    return SimilarityBreakdown(t, s, d, tpl, total, gate)


def _gate_reason(a: Signal, b: Signal, graph: DependencyGraph) -> str | None:
    """The hard gate. Returns why the pair is admissible, or None.

    Order matters only for the explanation string — a shared trace id is the
    strongest evidence available (it is literally the same request), so it is
    reported in preference to weaker justifications.
    """
    if a.trace_id and b.trace_id and a.trace_id == b.trace_id:
        return "shared trace_id"
    if a.service == b.service:
        return "same service"
    if graph.has_direct_edge(a.service, b.service):
        return "direct dependency edge"
    if a.parent_service == b.service or b.parent_service == a.service:
        return "observed caller/callee in trace"
    return None


# --------------------------------------------------------------------------
# blocking
# --------------------------------------------------------------------------


def candidate_pairs(
    signals: list[Signal], graph: DependencyGraph
) -> tuple[set[tuple[int, int]], dict[str, int]]:
    """Generate index pairs worth scoring, via blocking.

    Three block families, matching the three ways the gate can be satisfied.
    Any pair not landing in a shared block would fail the gate anyway, so
    skipping it costs no recall — this is a pure cost optimisation, not an
    accuracy trade.
    """
    by_service: dict[str, list[int]] = defaultdict(list)
    by_trace: dict[str, list[int]] = defaultdict(list)
    for i, signal in enumerate(signals):
        by_service[signal.service].append(i)
        if signal.trace_id:
            by_trace[signal.trace_id].append(i)

    pairs: set[tuple[int, int]] = set()

    for members in by_service.values():
        pairs.update(combinations(sorted(members), 2))
    for members in by_trace.values():
        pairs.update(combinations(sorted(members), 2))

    # Dependency-neighbour block, restricted by time so a service pair that is
    # adjacent in the graph but hours apart never becomes a candidate.
    window = timedelta(minutes=WINDOW_MAX_MIN)
    services = sorted(by_service)
    for idx, svc_a in enumerate(services):
        neighbours = graph.neighbours(svc_a)
        for svc_b in services[idx + 1:]:
            if svc_b not in neighbours:
                continue
            for i in by_service[svc_a]:
                for j in by_service[svc_b]:
                    if abs(signals[i].timestamp - signals[j].timestamp) <= window:
                        pairs.add((i, j) if i < j else (j, i))

    n = len(signals)
    stats = {
        "possible_pairs": n * (n - 1) // 2,
        "candidate_pairs": len(pairs),
    }
    return pairs, stats


