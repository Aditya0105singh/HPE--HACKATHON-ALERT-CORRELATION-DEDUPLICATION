@dataclass
class Cluster:
    cluster_id: int
    signals: list[Signal]
    gate_reasons: dict[str, int] = field(default_factory=dict)
    mean_similarity: float = 0.0
    confidence: float = 0.0

    @property
    def services(self) -> list[str]:
        return sorted({s.service for s in self.signals})

    @property
    def start(self):
        return min(s.timestamp for s in self.signals)

    @property
    def end(self):
        return max(s.timestamp for s in self.signals)


@dataclass
class CorrelationReport:
    input_signals: int = 0
    clustered: int = 0
    noise: int = 0
    clusters_formed: int = 0
    possible_pairs: int = 0
    candidate_pairs: int = 0
    scored_pairs: int = 0
    gate_rejected: int = 0


def correlate(
    signals: list[Signal], graph: DependencyGraph
) -> tuple[list[Cluster], list[Signal], CorrelationReport]:
    """Cluster anomalous signals into incidents.

    Only anomalous signals are considered — correlating everything would mean
    clustering healthy traffic, and the whole point of DETECT is to shrink
    what CORRELATE has to reason about.
    """
    anomalous = [s for s in signals if s.is_anomaly]
    report = CorrelationReport(input_signals=len(anomalous))

    if len(anomalous) < 2:
        report.noise = len(anomalous)
        return [], anomalous, report

    pairs, stats = candidate_pairs(anomalous, graph)
    report.possible_pairs = stats["possible_pairs"]
    report.candidate_pairs = stats["candidate_pairs"]

    rows: list[int] = []
    cols: list[int] = []
    data: list[float] = []
    breakdowns: dict[tuple[int, int], SimilarityBreakdown] = {}

    for i, j in pairs:
        result = similarity(anomalous[i], anomalous[j], graph)
        if result is None:
            report.gate_rejected += 1
            continue
        distance = 1.0 - result.total
        if distance > EPS:
            continue
        breakdowns[(i, j)] = result
        # Symmetric entries: DBSCAN reads the matrix in both directions.
        rows.extend([i, j])
        cols.extend([j, i])
        # A stored zero would be dropped by the sparse format and read back as
        # "not a neighbour" — the exact opposite of distance zero. Floor it.
        data.extend([max(distance, 1e-6)] * 2)

    report.scored_pairs = len(breakdowns)

    n = len(anomalous)
    matrix = csr_matrix((data, (rows, cols)), shape=(n, n))
    # sklearn scans each row assuming ascending distances; handing it an
    # unsorted graph works but re-sorts internally and warns every call.
    matrix = sort_graph_by_row_values(matrix, warn_when_not_sorted=False)
    labels = DBSCAN(eps=EPS, min_samples=MIN_SAMPLES, metric="precomputed").fit_predict(matrix)

    grouped: dict[int, list[int]] = defaultdict(list)
    for idx, label in enumerate(labels):
        grouped[int(label)].append(idx)

    noise = [anomalous[i] for i in grouped.pop(-1, [])]
    clusters: list[Cluster] = []
    for new_id, (_, members) in enumerate(sorted(grouped.items())):
        cluster = Cluster(
            cluster_id=new_id,
            signals=sorted((anomalous[i] for i in members), key=lambda s: s.timestamp),
        )
        _annotate(cluster, members, breakdowns)
        clusters.append(cluster)

    report.clusters_formed = len(clusters)
    report.clustered = sum(len(c.signals) for c in clusters)
    report.noise = len(noise)
    return clusters, noise, report


def near_misses(
    cluster: Cluster, noise: list[Signal], graph: DependencyGraph, limit: int = 4
) -> list[tuple[Signal, str]]:
    """Signals that fired near this incident but were deliberately excluded.

    Surfacing these is what lets a reviewer trust the grouping. "17 signals
    became 1 incident" is a claim; "and here is the disk-usage warning that
    fired inside the same window, excluded because it shares no service,
    dependency edge or trace" is evidence. It also makes a *wrong* exclusion
    catchable in seconds rather than during the next outage.
    """
    window = timedelta(minutes=WINDOW_MAX_MIN)
    out: list[tuple[Signal, str]] = []

    for signal in noise:
        if signal.timestamp < cluster.start - window or signal.timestamp > cluster.end + window:
            continue
        reason = _exclusion_reason(signal, cluster, graph)
        if reason:
            out.append((signal, reason))
        if len(out) >= limit:
            break
    return out


def _exclusion_reason(signal: Signal, cluster: Cluster, graph: DependencyGraph) -> str:
    """Name the specific gate condition this signal failed."""
    services = set(cluster.services)
    traces = {s.trace_id for s in cluster.signals if s.trace_id}

    if signal.service in services:
        return ""  # same service — it was excluded on similarity, not the gate
    if signal.trace_id and signal.trace_id in traces:
        return ""
    if any(graph.has_direct_edge(signal.service, svc) for svc in services):
        return "adjacent in the dependency graph but below the similarity threshold"
    return "no shared service, dependency edge, or trace id"


def _annotate(
    cluster: Cluster,
    members: list[int],
    breakdowns: dict[tuple[int, int], SimilarityBreakdown],
) -> None:
    """Record how a cluster was held together, and how much to trust it.

    Confidence is driven by the *weakest* kind of evidence used, not the
    average: a cluster joined mostly by shared trace ids but with one member
    attached by loose token overlap deserves a reviewer's attention on exactly
    that member. Reporting a comfortable mean would hide it.
    """
    inside = set(members)
    reasons: dict[str, int] = {}
    scores: list[float] = []
    for (i, j), breakdown in breakdowns.items():
        if i in inside and j in inside:
            reasons[breakdown.gate_reason] = reasons.get(breakdown.gate_reason, 0) + 1
            scores.append(breakdown.total)

    cluster.gate_reasons = dict(sorted(reasons.items(), key=lambda kv: -kv[1]))
    cluster.mean_similarity = float(np.mean(scores)) if scores else 0.0

    strong = reasons.get("shared trace_id", 0) + reasons.get("same service", 0)
    total = sum(reasons.values()) or 1
    strong_share = strong / total
    cluster.confidence = round(
        min(0.35 + 0.45 * strong_share + 0.30 * cluster.mean_similarity, 1.0), 2
    )
